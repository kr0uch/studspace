INSERT INTO bookings (
    user_id,
    space_id,
    first_name,
    last_name,
    patronymic,
    occupation,
    title,
    starts_at,
    ends_at,
    purpose,
    people_count,
    status,
    rescheduled_from_id
)
SELECT
    user_id,
    $2,
    first_name,
    last_name,
    patronymic,
    occupation,
    title,
    $3,
    $4,
    purpose,
    people_count,
    'pending',
    booking_id
FROM bookings
WHERE booking_id = $1
RETURNING
    booking_id,
    user_id,
    space_id,
    first_name,
    last_name,
    patronymic,
    occupation,
    title,
    starts_at,
    ends_at,
    purpose,
    people_count,
    status,
    reject_reason_title,
    reject_reason_text,
    decided_by,
    decided_at,
    cancelled_by,
